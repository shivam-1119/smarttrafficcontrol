# %% [markdown]
# # Smart Traffic Control - Prediction Model
# This notebook demonstrates an end-to-end pipeline for traffic prediction and green-light recommendation.
# 
# Steps included:
# 1. Prepare and clean historical traffic dataset
# 2. Create prediction features
# 3. Train traffic prediction model
# 4. Predict traffic for next 5/15 minutes
# 5. Predict future traffic density
# 6. Create simulated green-light recommendations
# 7. Evaluate model performance

# %%
import pandas as pd
import numpy as np
from sklearn.model_selection import train_test_split
from sklearn.ensemble import RandomForestRegressor
from sklearn.metrics import mean_squared_error, mean_absolute_error, r2_score
import matplotlib.pyplot as plt

# Optional: if xgboost is installed, we can use it, else fallback to RandomForest
try:
    import xgboost as xgb
    USE_XGB = True
    print("XGBoost found and will be used.")
except ImportError:
    USE_XGB = False
    print("XGBoost not found. Using Scikit-Learn RandomForestRegressor instead.")

# %% [markdown]
# ## 1. Prepare and clean historical traffic dataset
# Since we don't have a real dataset, we'll simulate a realistic traffic dataset for an intersection over 30 days.

# %%
def generate_traffic_data(days=30):
    np.random.seed(42)
    # 5-minute intervals for 'days'
    intervals = days * 24 * 12 
    dates = pd.date_range(start="2023-01-01", periods=intervals, freq="5min")
    
    data = []
    for dt in dates:
        # Base traffic depends on hour
        hour = dt.hour
        # Peak hours: 7-9 AM and 16-18 PM
        if 7 <= hour <= 9:
            base_vol = np.random.normal(120, 20)
        elif 16 <= hour <= 18:
            base_vol = np.random.normal(150, 25)
        elif 0 <= hour <= 5:
            base_vol = np.random.normal(15, 5) # Night time
        else:
            base_vol = np.random.normal(60, 15)
            
        # Weekend reduction
        if dt.weekday() >= 5:
            base_vol *= 0.6
            
        # Weather effect (0: clear, 1: rain)
        weather = np.random.choice([0, 1], p=[0.8, 0.2])
        if weather == 1:
            base_vol *= 0.8 # Slower traffic, fewer cars passing
            
        # Random noise and missing values simulation
        vol = max(0, int(base_vol))
        
        # Introduce some missing values randomly (2%)
        if np.random.random() < 0.02:
            vol = np.nan
            
        data.append([dt, vol, weather])
        
    df = pd.DataFrame(data, columns=['timestamp', 'vehicle_count', 'weather'])
    return df

print("Generating synthetic traffic data...")
raw_df = generate_traffic_data()

# Cleaning data
print("Cleaning data (Handling missing values)...")
# Forward fill missing vehicle counts
cleaned_df = raw_df.assign(
    vehicle_count=raw_df['vehicle_count'].ffill().astype(int)
)

print(cleaned_df.head())

# %% [markdown]
# ## 2. Create prediction features
# We extract time-based features and lagged features (past traffic) to predict future traffic.

# %%
def create_features(df):
    df = df.copy()
    # Time-based features
    df['hour'] = df['timestamp'].dt.hour
    df['day_of_week'] = df['timestamp'].dt.dayofweek
    df['is_weekend'] = df['day_of_week'].apply(lambda x: 1 if x >= 5 else 0)
    
    # Lagged features (past traffic)
    # Lag 1: 5 minutes ago, Lag 3: 15 minutes ago
    df['lag_1_5min'] = df['vehicle_count'].shift(1)
    df['lag_2_10min'] = df['vehicle_count'].shift(2)
    df['lag_3_15min'] = df['vehicle_count'].shift(3)
    
    # Target variables
    # We want to predict traffic for next 5 mins and next 15 mins (sum of next 3 intervals)
    df['target_next_5min'] = df['vehicle_count'].shift(-1)
    
    # Drop rows with NaN values generated by shifting
    df = df.dropna()
    return df

print("Creating features...")
features_df = create_features(cleaned_df)
print(features_df.head())

# %% [markdown]
# ## 3. Train traffic prediction model & 4. Predict traffic for next 5 minutes
# We will train a model to predict `target_next_5min`.

# %%
features = ['hour', 'day_of_week', 'is_weekend', 'weather', 'lag_1_5min', 'lag_2_10min', 'lag_3_15min']
X = features_df[features]
y_5min = features_df['target_next_5min']

# Time-series split (don't shuffle to respect temporal order)
X_train, X_test, y_train_5min, y_test_5min = train_test_split(X, y_5min, test_size=0.2, shuffle=False)

if USE_XGB:
    model_5min = xgb.XGBRegressor(n_estimators=100, learning_rate=0.1, random_state=42)
else:
    model_5min = RandomForestRegressor(n_estimators=100, random_state=42)

print("Training model for next 5-minute prediction...")
model_5min.fit(X_train, y_train_5min)

# Predict next 5 mins
preds_5min = model_5min.predict(X_test)


# %% [markdown]
# ## 5. Predict future traffic density
# We'll map the predicted vehicle count into a density category.

# %%
def get_density_category(vehicle_count):
    if vehicle_count < 30:
        return 'Low'
    elif vehicle_count < 80:
        return 'Medium'
    elif vehicle_count < 130:
        return 'High'
    else:
        return 'Severe'

# Add predictions and density to a results DataFrame
results_df = X_test.copy()
results_df['actual_5min'] = y_test_5min
results_df['predicted_5min'] = preds_5min
results_df['predicted_density'] = results_df['predicted_5min'].apply(get_density_category)

print("Predicted Traffic Density Sample:")
print(results_df[['predicted_5min', 'predicted_density']].head(10))

# %% [markdown]
# ## 6. Create simulated green-light recommendations
# Based on the predicted density, we suggest optimal green light durations.

# %%
def recommend_green_light(density):
    # Base recommendations in seconds
    if density == 'Low':
        return 20
    elif density == 'Medium':
        return 40
    elif density == 'High':
        return 60
    else: # Severe
        return 90

results_df['recommended_green_light_sec'] = results_df['predicted_density'].apply(recommend_green_light)

print("\nGreen-Light Recommendations based on Density:")
print(results_df[['predicted_5min', 'predicted_density', 'recommended_green_light_sec']].head(10))

# %% [markdown]
# ## 7. Evaluate model performance

# %%
def evaluate_model(y_true, y_pred, model_name="Model"):
    mse = mean_squared_error(y_true, y_pred)
    mae = mean_absolute_error(y_true, y_pred)
    r2 = r2_score(y_true, y_pred)
    
    print(f"--- {model_name} Evaluation ---")
    print(f"MSE: {mse:.2f}")
    print(f"MAE: {mae:.2f}")
    print(f"R2 Score: {r2:.4f}")

evaluate_model(y_test_5min, preds_5min, model_name="Traffic Prediction (Next 5 Min)")

# %%
# Visualizing a small slice of predictions vs actuals
plt.figure(figsize=(12, 6))
slice_idx = 200 # Plot 200 intervals
plt.plot(range(slice_idx), y_test_5min[:slice_idx], label='Actual', marker='.')
plt.plot(range(slice_idx), preds_5min[:slice_idx], label='Predicted', marker='.', alpha=0.7)
plt.title('Actual vs Predicted Traffic (5-min intervals)')
plt.xlabel('Interval')
plt.ylabel('Vehicle Count')
plt.legend()
plt.tight_layout()
plt.savefig('traffic_prediction_plot.png')
print("\nPlot saved as 'traffic_prediction_plot.png'")
